#include <stdio.h>

int main(void)
{
    // Store the number of completed lessons.
    int lessons = 7;

    /*
       Calculate and display the next lesson number.
       This block demonstrates a multi-line comment.
    */
    int nextLesson = lessons + 1;

    printf("Completed lessons: %d\n", lessons);
    printf("Next lesson: %d\n", nextLesson);

    return 0;
}
